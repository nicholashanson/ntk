#include <gtest/gtest.h>

#include <tls.hpp>

TEST( UnitTest, ParseServerHelloKeyShare ) {
	std::vector<uint8_t> key = { 0x60, 0xb5, 0x43, 0x35, 0x9c, 0x46, 0x02, 0x5d, 0x5d, 0x4d, 0x6c, 0x49, 0xba, 0x73, 0x12, 0xad,
								 0x83, 0x85, 0x98, 0xd3, 0x7c, 0xe1, 0x83, 0x9b, 0xa3, 0xdc, 0xb0, 0x11, 0xb8, 0x52, 0xee, 0x41 };
	std::vector<uint8_t> input = {
		0x00, 0x1d,
		0x00, 0x20, 
		0x60, 0xb5, 0x43, 0x35, 0x9c, 0x46, 0x02, 0x5d, 0x5d, 0x4d, 0x6c, 0x49, 0xba, 0x73, 0x12, 0xad,
		0x83, 0x85, 0x98, 0xd3, 0x7c, 0xe1, 0x83, 0x9b, 0xa3, 0xdc, 0xb0, 0x11, 0xb8, 0x52, 0xee, 0x41
	};
	auto parse_result = ntk::parse_server_hello_key_share( input );
	ASSERT_TRUE( parse_result ) << parse_result.error() << std::endl;
	auto& key_share = parse_result.value();
	EXPECT_EQ( key_share.group, ntk::named_group::x25519 );
	EXPECT_EQ( key_share.key_data, key );
}
